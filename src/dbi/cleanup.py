import os
import re
import glob
from src.dbi.utils import split_dbi_blocks, parse_issue_code_from_block
from src.utils import cover_filename


def cleanup_indexed_issues(dbi_paths: list[str]):
    """Removes blocks from the given DBI files that correspond to issues already indexed in Inducks.
    If a DBI file has no blocks left, it is deleted to keep the repository clean."""
    issue_codes_to_check = set()
    file_blocks = {}

    for path in dbi_paths:
        if not os.path.exists(path):
            continue
        try:
            with open(path, "r", encoding="utf-8") as f:
                content = f.read()
            country_prefix = os.path.basename(path).replace(".dbi", "").lower()
            parsed_blocks = []
            for cleaned_block in split_dbi_blocks(content):
                code = parse_issue_code_from_block(cleaned_block)
                if code:
                    clean_code = code.replace(" ", "").replace("_", "").lower()
                    if "/" not in clean_code:
                        clean_code = f"{country_prefix}/{clean_code}"
                    parsed_blocks.append((code, clean_code, cleaned_block))
                    issue_codes_to_check.add(clean_code)
                else:
                    parsed_blocks.append((code, None, cleaned_block))
            file_blocks[path] = parsed_blocks
        except Exception as e:
            print(f"  [warn] Failed to read {path} for cleanup: {e}")

    if not issue_codes_to_check:
        return

    search_list = list(issue_codes_to_check)
    query_items = set(search_list)
    for code in search_list:
        if '-' in code:
            query_items.add(code.split('-')[0])
    query_list = list(query_items)

    found_codes = set()
    print(f"  [DBI] Checking {len(query_list)} issue(s) against Inducks database...")
    from src.db import query_db
    try:
        # Process in batches of 100 to avoid overly large queries
        batch_size = 100
        for i in range(0, len(query_list), batch_size):
            batch = query_list[i:i+batch_size]
            placeholders = ','.join(['?'] * len(batch))
            query = f"SELECT issuecode, fullyindexed FROM inducks_issue WHERE LOWER(REPLACE(issuecode, ' ', '')) IN ({placeholders})"
            res = query_db(query, tuple(batch))
            for row in res:
                issuecode_clean = row[0].replace(" ", "").replace("_", "").lower()
                fully_indexed = row[1].strip().upper() if row[1] else ''
                if fully_indexed == 'Y':
                    found_codes.add(issuecode_clean)
    except Exception as e:
        print(f"  [warn] DB fetch failed: {e}")
        return

    if not found_codes:
        return

    def delete_cover_for_issue(issue_code: str, country_prefix: str):
        cover_path = os.path.join("covers", f"{cover_filename(issue_code, country_prefix)}.jpg")
        if os.path.exists(cover_path):
            try:
                os.remove(cover_path)
                print(f"  [Clean] Deleted cover image {os.path.basename(cover_path)}")
            except Exception as e:
                print(f"  [warn] Failed to delete cover {cover_path}: {e}")

    for path, parsed_blocks in file_blocks.items():
        kept_blocks = []
        country_prefix = os.path.basename(path).replace(".dbi", "").lower()

        for orig_code, clean_code, block in parsed_blocks:
            is_found = False
            if clean_code:
                if clean_code in found_codes:
                    is_found = True
                elif '-' in clean_code:
                    first_part = clean_code.split('-')[0]
                    if first_part in found_codes:
                        is_found = True

            if not is_found:
                kept_blocks.append(block)
            else:
                print(f"  [DBI] Issue {orig_code} is already in Inducks. Removing from {path}.")
                delete_cover_for_issue(orig_code, country_prefix)

        if len(kept_blocks) < len(parsed_blocks):
            if not kept_blocks:
                try:
                    os.remove(path)
                    print(f"  [DBI] All issues indexed in {path}: deleted file.")
                except Exception as e:
                    print(f"  [warn] Failed to remove empty {path}: {e}")
            else:
                header = "^^ Pre-index automatically generated by DisneyComicsWatcher\n\n"
                sorted_content = header + "\n\n".join(kept_blocks) + "\n\n"
                try:
                    with open(path, "w", encoding="utf-8") as f:
                        f.write(sorted_content)
                except Exception as e:
                    print(f"  [warn] Failed to rewrite {path}: {e}")


def cleanup_existing_covers(covers_dir: str = "covers"):
    """Scans all images in covers/ and deletes any that:
    1. Already have a cover scan uploaded on Inducks (inducks_entryurl has a matching entry), OR
    2. Belong to an issue that is already fully indexed in Inducks (fullyindexed == 'Y')."""
    if not os.path.isdir(covers_dir):
        return

    from src.db import query_db

    cover_files = (
        glob.glob(os.path.join(covers_dir, "*.jpg")) +
        glob.glob(os.path.join(covers_dir, "*.jpeg")) +
        glob.glob(os.path.join(covers_dir, "*.png"))
    )
    if not cover_files:
        return

    has_entryurl = bool(query_db("SELECT 1 FROM sqlite_master WHERE type='table' AND name='inducks_entryurl'"))
    has_issue = bool(query_db("SELECT 1 FROM sqlite_master WHERE type='table' AND name='inducks_issue'"))
    if not has_entryurl and not has_issue:
        return

    # 1. Parse all covers into issue candidate mappings
    file_candidates: dict[str, list[str]] = {}
    all_issue_candidates: set[str] = set()

    for fpath in cover_files:
        fname = os.path.basename(fpath)
        base, _ = os.path.splitext(fname)
        m = re.match(r'^([a-z]+)_(.+?)(?:a)?_\d+$', base, re.IGNORECASE)
        if not m:
            continue
        country = m.group(1).lower()
        inner = m.group(2).lower()
        inner_norm = re.sub(r'_0+(\d+)', r'\1', inner)

        cands = [
            f"{country}/{inner.replace('_', '')}",
            f"{country}/{inner_norm.replace('_', '')}",
        ]
        if country == "fr":
            for prefix in ("mp", "jm", "jmg", "dp", "pm", "spg", "tp"):
                cands.append(f"fr/{prefix}{inner.replace('_', '')}")
                cands.append(f"fr/{prefix}{inner_norm.replace('_', '')}")

        file_candidates[fpath] = cands
        all_issue_candidates.update(cands)

    if not all_issue_candidates:
        return

    # 2. Batch query inducks_issue for fully indexed status & matched issuecodes
    matched_issues: dict[str, tuple[str, bool]] = {}  # clean_code -> (issuecode, is_fully_indexed)
    cand_list = list(all_issue_candidates)
    batch_size = 200

    if has_issue:
        for i in range(0, len(cand_list), batch_size):
            batch = cand_list[i:i + batch_size]
            placeholders = ",".join(["?"] * len(batch))
            rows = query_db(
                f"SELECT issuecode, LOWER(REPLACE(issuecode, ' ', '')), fullyindexed FROM inducks_issue WHERE LOWER(REPLACE(issuecode, ' ', '')) IN ({placeholders})",
                tuple(batch)
            ) or []
            for issuecode, clean_code, fully_indexed in rows:
                is_full = bool(fully_indexed and fully_indexed.strip().upper() == 'Y')
                matched_issues[clean_code] = (issuecode, is_full)

    # 3. For issues that are NOT fully indexed, check if entryurl has the cover scan
    entrycodes_to_check: set[str] = set()
    issuecode_to_entrycodes: dict[str, list[str]] = {}

    for clean_code, (issuecode, is_full) in matched_issues.items():
        if not is_full and has_entryurl:
            ecs = [f"{issuecode}a", f"{issuecode} a"]
            issuecode_to_entrycodes[issuecode] = ecs
            entrycodes_to_check.update(ecs)

    scanned_entrycodes: set[str] = set()
    if entrycodes_to_check:
        ec_list = list(entrycodes_to_check)
        for i in range(0, len(ec_list), batch_size):
            batch = ec_list[i:i + batch_size]
            placeholders = ",".join(["?"] * len(batch))
            rows = query_db(
                f"SELECT DISTINCT entrycode FROM inducks_entryurl WHERE entrycode IN ({placeholders})",
                tuple(batch)
            ) or []
            for (ec,) in rows:
                scanned_entrycodes.add(ec)

    # 4. Determine obsolete files and delete
    deleted_count = 0
    for fpath, cands in file_candidates.items():
        fname = os.path.basename(fpath)
        is_obsolete = False
        for c in cands:
            if c in matched_issues:
                issuecode, is_full = matched_issues[c]
                if is_full:
                    is_obsolete = True
                    break
                if any(ec in scanned_entrycodes for ec in issuecode_to_entrycodes.get(issuecode, [])):
                    is_obsolete = True
                    break

        if is_obsolete:
            try:
                os.remove(fpath)
                deleted_count += 1
                print(f"  [Clean] Cover already on Inducks: removed {fname}")
            except Exception as e:
                print(f"  [warn] Failed to remove cover {fpath}: {e}")

    if deleted_count:
        print(f"  [Clean] Removed {deleted_count} obsolete cover(s) from {covers_dir}/.")
